"""Write the TypeScript wire types of the provider routes, read from their Python TypedDicts.

Sources: models/usage/provider_status.py (status), models/usage/provider_views.py
(model picker, usage, fallback, the provider_quota frame), models/listing/detected.py
(Add provider) and models/listing/key_check.py (the key check).

    python -m scripts.generators.generate_provider_status_types
"""
from __future__ import annotations

import typing
from pathlib import Path
from typing import Any, Literal, Union, get_args, get_origin, get_type_hints

from openprogram.models.listing import detected, key_check
from openprogram.models.usage import provider_status as schema
from openprogram.models.usage import provider_views as views

TARGET = Path(__file__).resolve().parents[2] / "apps/web/lib/settings/provider-status.generated.ts"
_ALIASES = {
    "HealthState": schema.HealthState, "QuotaKind": schema.QuotaKind, "Billing": schema.Billing,
    "FixAction": schema.FixAction, "Tone": schema.Tone, "UsageGroup": views.UsageGroup,
    "FallbackReason": views.FallbackReason, "AuthKind": detected.AuthKind, "CheckResult": key_check.CheckResult,
}
_RECORDS = (
    schema.QuotaLimitWire, schema.QuotaWire, schema.HealthWire, schema.SpendDay, schema.SpendWire,
    schema.KeyHealth, schema.FixWire, schema.WayLabel, schema.ProviderStatus, schema.ProviderQuotaFrame,
    schema.ProviderStatusPayload,
    views.PickerQuota, views.PickerBalance, views.PickerProvider, views.ProviderQuotaEvent,
    views.UsageTotals, views.DayModel, views.UsageDay, views.UsageModel, views.QuotaSample,
    views.ProviderUsage, views.FallbackModel, views.FallbackPayload,
    detected.ProviderChoice, detected.PopularProvider, detected.DetectedEnvKey, detected.DetectedLocal,
    detected.DetectedPayload,
    key_check.Balance, key_check.SuggestedModel, key_check.KeyCheck,
)
_RECORD_NAMES = {record: record.__name__ for record in _RECORDS}
_PRIMITIVES = {str: "string", int: "number", float: "number", bool: "boolean", type(None): "null", Any: "unknown"}


def _type(value: Any) -> str:
    for name, alias in _ALIASES.items():
        if value == alias:
            return name
    if value in _RECORD_NAMES:
        return _RECORD_NAMES[value]
    if value in _PRIMITIVES:
        return _PRIMITIVES[value]
    origin = get_origin(value)
    if origin is Literal:
        return " | ".join(f'"{item}"' for item in get_args(value))
    if origin is list:
        return f"{_type(get_args(value)[0])}[]"
    if origin is dict:
        key, item = get_args(value)
        return f"Record<{_type(key)}, {_type(item)}>"
    if origin is Union or isinstance(value, typing.types.UnionType):  # type: ignore[attr-defined]
        return " | ".join(_type(item) for item in get_args(value))
    raise TypeError(f"no TypeScript form for {value!r}")


def render() -> str:
    lines = [
        "// Generated by scripts/generators/generate_provider_status_types.py from the provider routes' TypedDicts. "
        "Do not edit.",
        "",
    ]
    lines += [
        f"export type {name} = {' | '.join(repr(item).replace(chr(39), chr(34)) for item in get_args(alias))};"
        for name, alias in _ALIASES.items()
    ]
    for record in _RECORDS:
        hints = get_type_hints(record)
        lines += ["", f"export interface {record.__name__} {{"]
        lines += [
            f"  {key}{'' if key in record.__required_keys__ else '?'}: {_type(hint)};"
            for key, hint in hints.items()
        ]
        lines.append("}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    TARGET.write_text(render(), encoding="utf-8")
