"use client"

// shadcn/ui Command, radix-nova style (the style ui.shadcn.com's docs use),
// copied from the official registry (/r/styles/radix-nova/command.json).
// Adaptations: the dialog is this app's Nova Dialog (overlay occludes
// native web views); the search field
// renders the registry's InputGroup classes inline with a leading lucide
// icon instead of pulling in input-group; the selected row uses bg-accent,
// the highlight every menu uses (bg-muted sits on --popover in dark themes).

import * as React from "react"
import { Command as CommandPrimitive } from "cmdk"
import { Check, Search } from "lucide-react"

import { cn } from "@/lib/utils"
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog"

function Command({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive>) {
  return (
    <CommandPrimitive
      data-slot="command"
      className={cn(
        "flex size-full flex-col overflow-hidden rounded-xl! bg-popover p-1 text-popover-foreground",
        className
      )}
      {...props}
    />
  )
}

function CommandDialog({
  title = "Command Palette",
  description = "Search for a command to run...",
  children,
  className,
  showCloseButton = false,
  ...props
}: React.ComponentProps<typeof Dialog> & {
  title?: string
  description?: string
  className?: string
  showCloseButton?: boolean
}) {
  return (
    <Dialog {...props}>
      <DialogHeader className="sr-only">
        <DialogTitle>{title}</DialogTitle>
        <DialogDescription>{description}</DialogDescription>
      </DialogHeader>
      <DialogContent
        className={cn(
          "top-1/3 translate-y-0 overflow-hidden rounded-xl! p-0 shadow-(--popover-shadow) transition-shadow hover:shadow-(--popover-shadow-hover) ring-(color:--popover-ring)",
          className
        )}
        showCloseButton={showCloseButton}
      >
        {children}
      </DialogContent>
    </Dialog>
  )
}

function CommandInput({
  className,
  ...props
}: React.ComponentProps<typeof CommandPrimitive.Input>) {
  return (
    <div data-slot="command-input-wrapper" className="p-1 pb-0">
      <div
        data-slot="input-group"
        role="group"
        className="group/input-group relative flex h-(--ui-button-h-sm)! w-full min-w-0 items-center gap-2 rounded-lg! border border-input/30 bg-input/30 pl-2 transition-colors outline-none"
      >
        <Search className="size-4 shrink-0 opacity-50" aria-hidden="true" />
        <CommandPrimitive.Input
          data-slot="command-input"
          className={cn(
            "w-full bg-transparent text-fs-base outline-hidden placeholder:text-muted-foreground disabled:cursor-not-allowed disabled:opacity-50",
            className
          )}
          {...props}
        />
      </div>
    </div>
  )
}

