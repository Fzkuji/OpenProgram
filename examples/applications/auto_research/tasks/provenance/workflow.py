"""writing_provenance: where each paragraph of the paper came from, by Git history.

Learned from Grammarly Authorship, which records whether each passage was typed,
generated by AI, edited by AI or pasted, and replays how it was written as evidence for
an AI-use disclosure. Here the record is the project's Git history and the run trails
Auto Research writes. Plain code, no model calls, deterministic.
"""

import json
from collections import Counter
from difflib import SequenceMatcher
from pathlib import Path

from auto_research.trail import Trail

from ..overlap import match
from ..overlap.prose import COMMENT, sentences
from ..submission import common
from . import history, page, paragraphs
from . import sources as source_texts

CLASSES = ("human", "ai", "ai_edit", "pasted", "bulk", "uncommitted")
NAMES = {"human": "作者撰写", "ai": "AI 生成", "ai_edit": "AI 修改", "pasted": "粘贴（与已有文本重合）",
         "bulk": "大段一次加入", "uncommitted": "未提交"}
PASTE_WORDS = 120       # words of one paragraph added by one commit that count as a large single insert
MAX_VERSIONS = 30       # versions of a paragraph kept in its replay
EDIT_COVER = 0.6        # share of an applied edit's new words that must be found in the paragraph
MAX_HOPS = 3            # files a paragraph's history is followed back through (moves into \input files)
MATCH_RATIO = 0.4       # word similarity for an older version to count as the same paragraph


def writing_provenance(paper_dir: str, out_dir: str = "") -> str:
    """Record where each paragraph of the paper came from, from the project's Git history.

    paper_dir is the paper's Git repository; the main .tex is rules.json's main_tex or
    the top-level .tex with \\documentclass, and its \\input files are followed. Each
    word gets the commit that wrote it, by a word diff of the paragraph's versions across
    the commits that changed its file; the words of its first version take their line's
    git blame (--porcelain -w -M -C, which follows moves and copies). A word's class is
    its commit's: ai (a Co-Authored-By trailer naming an AI tool, or an Auto Research
    run), ai_edit (changed by an edit from a paper_proofread, writing_style or
    caption_check edits.json that this commit applied), pasted (one commit added 120 or more words of
    the paragraph and they repeat a cited work or own paper text_overlap has on disk),
    bulk (such an insert that repeats nothing found), uncommitted, or human. Each
    paragraph gets its shares, first and last commit and a replay of at most 30
    versions. Writes provenance.html, provenance.json and report.md (Chinese, with a
    draft disclosure sentence) to out_dir/<timestamp>/ (default
    <paper_dir>/drafts/writing_provenance). PASS, or PASS_WITH_NOTES when the paper has
    uncommitted changes.
    """
    paper = common.repo(paper_dir)
    main = common.main_tex(paper)
    if main is None:
        raise ValueError(f"{paper} has no main .tex (rules.json main_tex or a top-level .tex with \\documentclass)")
    rel_main = main.relative_to(paper).as_posix()
    paras = paragraphs.read(paper, rel_main)
    if not paras:
        raise ValueError(f"{rel_main} has no prose")
    out = common.run_folder(paper, out_dir, "writing_provenance")
    trail = Trail("writing_provenance", {"paper_dir": str(paper), "out_dir": out_dir}, {})
    files = list(dict.fromkeys([rel_main] + [p["file"] for p in paras]))
    trail.step("paragraphs", files=files, paragraphs=len(paras))

    info = history.commits(paper)
    store = history.Files(paper)
    blames = {f: history.blame(paper, f, len((paper / f).read_text(encoding="utf-8", errors="ignore").splitlines()))
              for f in files}
    edits = history.load_edits(paper)
    dirty = history.dirty(paper, files)
    trail.step("history", commits=len(info), ai_commits=sum(c["class"] == "ai" for c in info.values()),
               edits=len(edits), dirty=dirty)

    for p in paras:
        p["chain"] = chain(p, store, rel_main, [blames[p["file"]][line["line"] - 1] for line in p["lines"]])
    applied = classify(paras, blames, info, store, edits)
    found, problems = inserts(paper, paras, info)
    trail.step("classes", applied_edits=len(applied), inserts=len(found), source_problems=problems)
    for p in paras:
        p["replay"] = replay(p, info)
    record = summarize(paper, rel_main, paras, info, applied, found, dirty, problems)
    trail.step("replay", versions=sum(len(p["replay"]["versions"]) for p in paras))

    (out / "provenance.json").write_text(json.dumps(record, ensure_ascii=False, indent=2), encoding="utf-8")
    (out / "provenance.html").write_text(page.render(record), encoding="utf-8")
    (out / "report.md").write_text(render(record), encoding="utf-8")
    trail.step("report", status=record["status"], shares=record["shares"])
    run = trail.save(out, report=out / "report.md", json=out / "provenance.json", html=out / "provenance.html")
    return json.dumps({"status": record["status"], "report": str(out / "report.md"),
                       "json": str(out / "provenance.json"), "html": str(out / "provenance.html"), "run": str(run),
                       "words": record["words"], "shares": record["shares"],
                       "ai_paragraphs": len(record["ai_passages"]),
                       "pasted": [i for i in record["inserts"] if i["kind"] == "pasted"],
                       "bulk": sum(i["kind"] == "bulk" for i in record["inserts"]),
                       "uncommitted_files": dirty, "disclosure": record["disclosure"]["en"]},
                      ensure_ascii=False)


# Versions ---------------------------------------------------------------------------

def similarity(a: list[str], b: list[str]) -> float:
    m = SequenceMatcher(None, a, b, autojunk=False)
    return m.ratio() if m.real_quick_ratio() >= MATCH_RATIO and m.quick_ratio() >= MATCH_RATIO else 0.0


def tokens(paragraph: dict) -> list[str]:
    return [t for line in paragraph["lines"] for t, _ in line["tokens"]]


def chain(p: dict, store: history.Files, rel_main: str, blamed: list[dict]) -> list[tuple[str, list[str], str]]:
    """The versions of the paragraph, oldest first, as (commit, shown tokens, file):
    walking the commits that changed its file from the newest, each version is the
    paragraph of that commit most like the one after it, until none is alike. When the
    line blame says the oldest version's lines came from another file (a paragraph moved
    into an \\input file), the walk goes on in that file from the commit blamed, up to
    MAX_HOPS times. A version equal to the one before is dropped (the older commit wrote
    it). The working tree comes last, with the uncommitted mark, when it differs."""
    target = paragraphs.norm_words(p)
    found: list[tuple[str, list[str], str]] = []
    rel, start, visited = p["file"], "HEAD", set()
    for _ in range(MAX_HOPS + 1):
        visited.add(rel)
        for sha in store.log(rel, start):
            key = (sha, rel)
            if key not in store.splits:
                text = store.at(sha, rel)
                store.splits[key] = paragraphs.split(text, rel, rel == rel_main) if text else []
            scored = [(similarity(target, paragraphs.norm_words(c)), c) for c in store.splits[key]]
            best = max(scored, key=lambda x: x[0], default=(0.0, None))
            if best[1] is None or best[0] < MATCH_RATIO:
                break
            found.append((sha, tokens(best[1]), rel))
            target = paragraphs.norm_words(best[1])
        oldest = found[-1][0] if found else ""
        elsewhere = Counter((b["file"], b["sha"]) for b in blamed
                            if b["file"] not in visited and b["sha"] != history.UNCOMMITTED
                            and (not oldest or store.ancestor(b["sha"], oldest)))
        if not elsewhere:
            break
        (rel, start), _ = elsewhere.most_common(1)[0]
    out: list[tuple[str, list[str], str]] = []
    for sha, toks, rel in reversed(found):
        if not out or out[-1][1] != toks:
            out.append((sha, toks, rel))
    now = tokens(p)
    if not out or out[-1][1] != now:
        out.append((history.UNCOMMITTED, now, p["file"]))
    return out


def origins(versions: list[tuple]) -> list[str | None]:
    """For each token of the last version, the commit that wrote it: tokens kept from the
    version before inherit its commit, changed ones take the new commit. None marks a
    token of the first version, whose commit the line blame decides."""
    if not versions:
        return []
    owner: list[str | None] = [None] * len(versions[0][1])
    for (_, before, *_), (sha, after, *_) in zip(versions, versions[1:]):
        new: list[str | None] = [sha] * len(after)
        for op, i1, i2, j1, j2 in SequenceMatcher(None, before, after, autojunk=False).get_opcodes():
            if op == "equal":
                new[j1:j2] = owner[i1:i2]
        owner = new
    return owner


# Classes ----------------------------------------------------------------------------

def classify(paras: list[dict], blames: dict, info: dict, store: history.Files, edits: list[dict]) -> list[dict]:
    """Give every token of every paragraph its commit and class: word level from the
    paragraph's versions, the line blame (which follows moves and copies) for the words of
    its first version. Returns the edits found applied."""
    done: dict[tuple[str, str], list[dict]] = {}
    new_words: dict[int, list[str]] = {}
    for p in paras:
        first, first_file = (p["chain"][0][0], p["chain"][0][2]) if p["chain"] else (history.UNCOMMITTED, p["file"])
        owner = origins(p["chain"])
        file_of = {sha: rel for sha, _, rel in p["chain"]}
        flat, k = [], 0
        for line in p["lines"]:
            b = blames[p["file"]][line["line"] - 1]
            line["sha"] = b["sha"]
            for text, w in line["tokens"]:
                if k < len(owner) and owner[k] is not None:
                    sha, rel = owner[k], file_of.get(owner[k], p["file"])
                else:
                    sha, rel = first, first_file
                if (k >= len(owner) or owner[k] is None) and older(b["sha"], first, info, store):
                    sha, rel = b["sha"], b["file"]
                base = "uncommitted" if sha == history.UNCOMMITTED else info.get(sha, {}).get("class", "human")
                flat.append({"line": line, "text": text, "w": w, "sha": sha, "file": rel, "base": base,
                             "cls": base if w else ""})
                k += 1
        p["flat"] = flat
        classes = [t["cls"] for t in flat]
        for key in dict.fromkeys((t["sha"], t["file"]) for t in flat):
            if key not in done:
                done[key] = history.applied(store, key[0], key[1], edits)
            for e in done[key]:
                rep = new_words.setdefault(id(e), paragraphs.words(e["replacement"]))
                if mark(classes, flat, key, rep):
                    e.setdefault("paragraphs", set()).add(p["id"])
        for t, c in zip(flat, classes):
            t["cls"] = c
    seen, out = set(), []
    for (sha, rel), found in done.items():
        for e in found:
            if id(e) in seen:
                continue
            seen.add(id(e))
            out.append({"commit": sha[:7], "file": rel, "workflow": e["workflow"], "run": e["run"], "id": e["id"],
                        "paragraphs": sorted(e.get("paragraphs", ()), key=lambda x: int(x[1:]))})
    return out


def older(blamed: str, first: str, info: dict, store: history.Files) -> bool:
    """The line blame names a commit before the paragraph's first version here: the text
    was moved or copied from elsewhere, and that commit wrote it."""
    if blamed == history.UNCOMMITTED or blamed not in info:
        return False
    if first == history.UNCOMMITTED or first not in info:
        return True
    return store.ancestor(blamed, first)


def mark(classes: list[str], flat: list[dict], key: tuple[str, str], rep: list[str]) -> bool:
    """Find the edit's new text in the paragraph (runs of three or more of its words
    covering most of it) and mark as ai_edit the words in that span that the applying
    commit wrote: the words the edit changed. False when the new text is not here."""
    counted = [(i, t["w"]) for i, t in enumerate(flat) if t["w"]]
    words = [w for _, w in counted]
    if not words or not rep:
        return False
    blocks = [b for b in SequenceMatcher(None, words, rep, autojunk=False).get_matching_blocks()
              if b.size >= 3 or (b.size and b.size == len(rep))]
    if sum(b.size for b in blocks) < EDIT_COVER * len(rep):
        return False
    for j in range(blocks[0].a, blocks[-1].a + blocks[-1].size):
        i = counted[j][0]
        if (flat[i]["sha"], flat[i]["file"]) == key:
            classes[i] = "ai_edit"
    return True


def inserts(paper: Path, paras: list[dict], info: dict) -> tuple[list[dict], list[str]]:
    """Large single inserts: one human commit that wrote PASTE_WORDS or more words of a
    paragraph. Pasted when the words repeat a source text_overlap has on disk, else bulk."""
    loaded = None
    problems: list[str] = []
    found = []
    for p in paras:
        by_sha: dict[str, list[dict]] = {}
        for t in p["flat"]:
            if t["cls"] == "human":
                by_sha.setdefault(t["sha"], []).append(t)
        for sha, toks in by_sha.items():
            if len(toks) < PASTE_WORDS:
                continue
            if loaded is None:
                loaded, problems = source_texts.load(paper)
            text = " ".join(t["text"] for t in toks)
            sents = sentences([(p["file"], toks[0]["line"]["line"], text, False)])
            matches, _, _ = match.find(sents, loaded) if loaded else ([], 0, 0)
            best = max(matches, key=lambda m: (m["words"], m["overlap"]), default=None)
            kind = "pasted" if best else "bulk"
            for t in toks:
                t["cls"] = kind
            item = {"paragraph": p["id"], "commit": sha[:7], "date": info.get(sha, {}).get("date", ""),
                    "words": len(toks), "kind": kind}
            if best:
                src = next(s for s in loaded if s["id"] == best["source"])
                item.update(source=src["id"], title=src["title"], key=src["key"], matched_words=best["words"],
                            overlap=round(best["overlap"], 2), cited=best["cited"])
            p.setdefault("inserts", []).append(item)
            found.append(item)
    return found, problems


# Replay -----------------------------------------------------------------------------

def replay(p: dict, info: dict) -> dict:
    """The paragraph's versions for the page, oldest first, each with its word diff
    against the one before; at most MAX_VERSIONS (the first and the latest)."""
    versions = []
    for sha, toks, rel in p["chain"]:
        c = info.get(sha, {})
        if sha == history.UNCOMMITTED:
            c = {"subject": "未提交的改动", "class": "uncommitted"}
        versions.append({"commit": "" if sha == history.UNCOMMITTED else sha[:7], "date": c.get("date", ""),
                         "author": c.get("author", ""), "subject": c.get("subject", ""),
                         "class": c.get("class", "human"), "tools": c.get("tools", []), "file": rel,
                         "tokens": toks})
    omitted = max(0, len(versions) - MAX_VERSIONS)
    if omitted:
        versions = versions[:1] + versions[-(MAX_VERSIONS - 1):]
    before: list[str] = []
    for v in versions:
        toks = v.pop("tokens")
        v["text"] = " ".join(toks)
        v["diff"] = diff(before, toks)
        before = toks
    return {"versions": versions, "omitted": omitted}


def diff(a: list[str], b: list[str]) -> list[list[str]]:
    out = []
    for op, i1, i2, j1, j2 in SequenceMatcher(None, a, b, autojunk=False).get_opcodes():
        if op == "equal":
            out.append(["eq", " ".join(b[j1:j2])])
            continue
        if i2 > i1:
            out.append(["del", " ".join(a[i1:i2])])
        if j2 > j1:
            out.append(["ins", " ".join(b[j1:j2])])
    return out


# Summary ----------------------------------------------------------------------------

def shares(counts: Counter) -> dict:
    total = sum(counts.values())
    return {c: round(100 * counts.get(c, 0) / total, 1) if total else 0.0 for c in CLASSES}


def summarize(paper, rel_main, paras, info, applied, found, dirty, problems) -> dict:
    total, by_section = Counter(), {}
    out_paras, used = [], {}
    for p in paras:
        counts = Counter(t["cls"] for t in p["flat"] if t["cls"])
        total.update(counts)
        by_section.setdefault(p["section"], Counter()).update(counts)
        shas = {t["sha"] for t in p["flat"] if t["w"]}
        committed = sorted((info[s] for s in shas if s in info), key=lambda c: c["date"])
        for c in committed:
            used[c["sha"]] = c
        segments = []
        for t in p["flat"]:
            cls = t["cls"] or t["base"]
            if segments and segments[-1][0] == cls:
                segments[-1][1] += " " + t["text"]
            else:
                segments.append([cls, t["text"]])
        out_paras.append({
            "id": p["id"], "file": p["file"], "start": p["start"], "end": p["end"], "section": p["section"],
            "words": sum(counts.values()), "counts": {c: counts.get(c, 0) for c in CLASSES if counts.get(c)},
            "shares": shares(counts), "dominant": max(CLASSES, key=lambda c: counts.get(c, 0)),
            "first_commit": brief(committed[0]) if committed else None,
            "last_commit": brief(committed[-1]) if committed else None,
            "uncommitted": history.UNCOMMITTED in shas,
            "commits": [brief(c) for c in committed], "inserts": p.get("inserts", []),
            "segments": segments, "replay": p["replay"]})
    sections = [{"name": name, "words": sum(c.values()), "counts": dict(c), "shares": shares(c)}
                for name, c in by_section.items()]
    ai_passages = [{"paragraph": p["id"], "where": f"{p['file']}:{p['start']}-{p['end']}", "section": p["section"],
                    "ai": p["counts"].get("ai", 0), "ai_edit": p["counts"].get("ai_edit", 0), "words": p["words"],
                    "tools": sorted({t for c in p["commits"] for t in c["tools"]}),
                    "excerpt": excerpt(p["segments"])}
                   for p in out_paras if p["counts"].get("ai") or p["counts"].get("ai_edit")]
    ai_shas = {t["sha"] for p in paras for t in p["flat"] if t["cls"] == "ai"}
    tools = sorted({t for sha in ai_shas for t in info.get(sha, {}).get("tools", [])})
    workflows = sorted({a["workflow"] for a in applied if a["paragraphs"]})
    status = "PASS_WITH_NOTES" if dirty or total.get("uncommitted") else "PASS"
    record = {"status": status, "paper_dir": str(paper), "main_tex": rel_main,
              "files": sorted({p["file"] for p in paras}), "words": sum(total.values()),
              "counts": {c: total.get(c, 0) for c in CLASSES}, "shares": shares(total), "classes": NAMES,
              "sections": sections, "paragraphs": out_paras, "ai_passages": ai_passages, "inserts": found,
              "edits_applied": applied, "ai_tools": tools, "edit_workflows": workflows,
              "uncommitted_files": dirty, "source_problems": problems,
              "commits": len(used)}
    record["disclosure"] = disclosure(record)
    return record


def brief(c: dict) -> dict:
    return {"sha": c["sha"], "short": c["short"], "date": c["date"], "author": c["author"],
            "subject": c["subject"], "class": c["class"], "tools": c["tools"]}


def excerpt(segments: list, limit: int = 160) -> str:
    text = " ".join(t for _, t in segments)
    return text if len(text) <= limit else text[:limit].rsplit(" ", 1)[0] + " …"


def disclosure(r: dict) -> dict:
    """A draft sentence for the AI-use statement whose numbers are the record's."""
    s, tools, flows = r["shares"], r["ai_tools"], r["edit_workflows"]
    n = sum(1 for a in r["edits_applied"] if a["paragraphs"])
    names = {"paper_proofread": "proofreading", "writing_style": "style editing", "caption_check": "caption checking"}
    flow_en = ", ".join(names.get(w, w) for w in flows) or "editing"
    flow_zh = "、".join(history.EDIT_WORKFLOWS.get(w, w) for w in flows) or "修改"
    tool_en = ", ".join(tools) or "AI assistants"
    tool_zh = "、".join(tools) or "AI 助手"
    if not s["ai"] and not s["ai_edit"]:
        return {"en": "According to the project's version history, no part of the manuscript text was generated or "
                      "edited by AI tools; all text was written by the authors.",
                "zh": "根据项目的版本记录，论文正文没有由 AI 工具生成或修改的部分，全部由作者撰写。"}
    en, zh = [], []
    if s["ai"]:
        en.append(f"{s['ai']}% of the manuscript text (by word count) was first drafted with AI assistance "
                  f"({tool_en})")
        zh.append(f"论文正文中 {s['ai']}%（按词数）由 AI 协助起草（{tool_zh}）")
    if s["ai_edit"]:
        en.append(f"{s['ai_edit']}% of the words come from {n} wording edit{'s' if n > 1 else ''} proposed by AI "
                  f"{flow_en} tools, which the authors reviewed and accepted")
        zh.append(f"{s['ai_edit']}% 的词来自 AI {flow_zh}工具提出、经作者审阅采纳的 {n} 处措辞修改")
    rest = round(100 - s["ai"] - s["ai_edit"], 1)
    return {"en": "; ".join(en) + f"; the remaining {rest}% was written without AI assistance. The authors reviewed all "
                                  "AI-assisted text and take full responsibility for the content.",
            "zh": "；".join(zh) + f"；其余 {rest}% 未经 AI 协助。作者审阅了全部 AI 协助的文字，并对内容负全部责任。"}


# Report -----------------------------------------------------------------------------

def render(r: dict) -> str:
    lines = ["# 写作溯源", "",
             f"结论：{r['status']}　正文 {r['words']} 词，{len(r['paragraphs'])} 段，涉及 {r['commits']} 个提交。"
             "依据是仓库的 Git 历史（逐词对比各版本，加上 git blame）和 Auto Research 的运行记录，不调用模型。", ""]
    if r["uncommitted_files"]:
        lines += [f"论文有未提交的改动（{'、'.join(r['uncommitted_files'])}），这部分文字记为“未提交”，"
                  "提交后再运行即可归类。", ""]
    lines += ["## 总体", "", "| 类别 | 词数 | 占比 |", "|---|---|---|"]
    lines += [f"| {NAMES[c]} | {r['counts'][c]} | {r['shares'][c]}% |" for c in CLASSES if r["counts"][c]]
    lines += ["", "## 分节", "", "| 节 | 词数 | 作者 | AI 生成 | AI 修改 | 粘贴 | 大段加入 | 未提交 |",
              "|---|---|---|---|---|---|---|---|"]
    for s in r["sections"]:
        sh = s["shares"]
        lines.append(f"| {s['name']} | {s['words']} | {sh['human']}% | {sh['ai']}% | {sh['ai_edit']}% | "
                     f"{sh['pasted']}% | {sh['bulk']}% | {sh['uncommitted']}% |")
    lines += ["", "## AI 参与的段落", ""]
    if r["ai_passages"]:
        lines += ["| 段落 | 位置 | 节 | AI 生成词 | AI 修改词 | 工具 | 开头 |", "|---|---|---|---|---|---|---|"]
        for a in r["ai_passages"]:
            text = a["excerpt"].replace("|", "\\|")
            lines.append(f"| {a['paragraph']} | `{a['where']}` | {a['section']} | {a['ai']} | {a['ai_edit']} | "
                         f"{'、'.join(a['tools']) or '—'} | {text} |")
    else:
        lines.append("没有。")
    if r["edits_applied"]:
        lines += ["", "已采纳的 AI 修改（edits.json 中的修改被提交应用）：", ""]
        lines += [f"- 提交 `{a['commit']}` 应用了 {history.EDIT_WORKFLOWS.get(a['workflow'], a['workflow'])} "
                  f"`{a['run']}` 的 {a['id']}（{'、'.join(a['paragraphs']) or '段落已改写'}）"
                  for a in r["edits_applied"]]
    pasted = [i for i in r["inserts"] if i["kind"] == "pasted"]
    bulk = [i for i in r["inserts"] if i["kind"] == "bulk"]
    lines += ["", "## 大段一次加入", ""]
    if not r["inserts"]:
        lines.append(f"没有一次提交加入同一段 {PASTE_WORDS} 词以上的情况。")
    for i in pasted:
        lines.append(f"- {i['paragraph']}：提交 `{i['commit']}` 一次加入 {i['words']} 词，其中 {i['matched_words']} 词"
                     f"与 {i['title']}（{i['source']}）重合 {round(i['overlap'] * 100)}%"
                     f"{'，段内有引用' if i['cited'] else '，段内没有引用'}。请确认已引用或改写。")
    for i in bulk:
        lines.append(f"- {i['paragraph']}：提交 `{i['commit']}` 一次加入 {i['words']} 词，与已缓存的引用文献和"
                     "作者旧文都不重合。只是记录，不代表来源有问题（可能是从别处整理后一次提交）。")
    if r["source_problems"]:
        lines += ["", "读不了的对照文本：" + "、".join(r["source_problems"])]
    lines += ["", "## AI 使用声明草稿", "", "数字和上面的总体表一致，请核对后再用：", "",
              "> " + r["disclosure"]["en"], "", "> " + r["disclosure"]["zh"], "",
              "## 说明", "",
              "- 每个词归到写下它的提交：逐词对比这一段在各个提交中的版本；段落最早版本里的词按 git blame"
              "（忽略空白，跟踪移动和复制）。提交说明里有 Co-Authored-By 署名 AI 工具，或由 Auto Research 运行提交的，"
              "记为 AI 生成。",
              "- 校对、写作风格、图表标题检查的 edits.json 里的修改，被某个提交原样应用时，这处修改改动的词记为 AI 修改"
              "（没改动的词仍归原作者）。",
              "- 粘贴只在一次提交加入同一段 120 词以上、且与 text_overlap 缓存的引用文献或作者旧文重合时判定；"
              "AI 写在仓库外再粘进来的文字，Git 无法区分，会记为作者撰写。",
              "- provenance.html 里点一段可以回放它在各个提交中的版本。", ""]
    return "\n".join(lines)


